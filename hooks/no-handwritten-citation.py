#!/usr/bin/env python3
r"""PreToolUse(Write|Edit) hook: a citation is FETCHED, never AUTHORED.

WHY (2026-08-14). Four entries in an ACCEPTED manuscript carried wrong data: two
DOIs pointing at unrelated papers, one DOI that 404s for a paper that does not exist, and
paraphrased titles with truncated author lists on all four. The library was not the source. It
held the CORRECT values for two of them (reindl2017stingray -> slw175, not slw177;
evans2020sakurai -> staa343, not staa326). Someone wrote @article{} blocks BY HAND instead of
pulling from /papers. The failure was bypassing the wrapper, not the wrapper being wrong.

    AN AGENT SKIPS A WRAPPER EXACTLY WHEN IT BELIEVES THE UNDERLYING PRIMITIVE IS SIMPLE.

That is agent-comms #203, and a bib entry is the purest case of it: nobody hand-rolls Marp,
everybody hand-rolls a citation. It looks like six fields of typing.

THE SIGNATURE THIS GUARDS AGAINST. Paraphrased titles, truncated author lists, DOIs plausible and
wrong by two characters, one DOI for a paper that does not exist. That is metadata generated from
MEMORY rather than fetched -- what a language model produces when asked for a citation. The reader
this is written for is a session that believes it is being helpful, which is why the message names
the fetch command instead of just refusing.

=== PROHIBITION WITH A DECLARED ESCAPE HATCH ===

On the fleet's axis (agent-roster/agents.md, "Choosing a guard's mode: from REVERSIBILITY"):

  * A wrong citation in an accepted manuscript is IRREVERSIBLE -- that is exactly what happened,
    so this is not a recall aid. No marker file, no "run it again and it proceeds".
  * But hand-writing an entry is SOMETIMES LEGITIMATE -- a book chapter, a thesis, a private
    communication, anything with no DOI. A blanket refusal with no exit gets resented and switched
    off, and a disabled guard protects nothing.

So: refused every time, EXCEPT when the file declares

    % HAND-CITATION: <reason>

which makes the exception explicit, auditable, and LOGGED (~/.cache/no-handwritten-citation/
declarations.jsonl). That is the one improvement over plots-use-library.py, whose hatch exits
silently: a bypass nobody can count is a bypass nobody can review.

=== WHAT IT DOES NOT FIRE ON (the noise budget is spent on true positives) ===

  * references.bib and anything else under the papers library -- /papers GENERATES those, and a
    guard that blocks the tool's own output blocks the fix. (skill-first.py carries the same
    self-exemption; copied deliberately.)
  * .bbl files -- \bibitem appears in every compiled .bbl. Without this the hook would fire on
    ordinary LaTeX builds and be switched off within a day. This exclusion is not optional.
  * Any file that is not .bib/.bibtex/.tex. Prose ABOUT bibtex -- a report, a CLAUDE.md, a
    skill doc quoting `@article{` as an example -- is documentation, not a citation.
  * Reformatting/moving: an Edit whose citation keys ALL already exist in the old text is a
    reflow, not new content. Only NEW citation content is blocked.

    no-handwritten-citation.py --selftest    # must-block AND must-allow halves; both required
    no-handwritten-citation.py --log         # read the declared exceptions
"""
import json
import os
import re
import sys

LOG = os.path.expanduser("~/.cache/no-handwritten-citation/declarations.jsonl")

# A BibTeX entry being authored. Anchored at @ + type + brace so `@article` in prose is not a hit.
BIB_ENTRY = re.compile(
    r"@\s*(article|inproceedings|incollection|inbook|book|booklet|phdthesis|mastersthesis|"
    r"techreport|unpublished|conference|proceedings|misc)\s*[{(]", re.I)

# \bibitem{key} or \bibitem[label]{key} -- the thebibliography form some manuscripts carry.
BIBITEM = re.compile(r"\\bibitem\s*(?:\[[^\]]*\])?\s*\{", re.I)

# Cite keys, used to tell "new entry" from "reflowed existing entry".
BIB_KEY = re.compile(
    r"@\s*[a-z]+\s*[{(]\s*([^,\s}]+)|\\bibitem\s*(?:\[[^\]]*\])?\s*\{([^}]+)\}", re.I)

# Declared exception. `%` is the comment char in both .bib and .tex; `#` accepted for generality.
ESCAPE_HATCH = re.compile(r"(?:%|#)\s*HAND-CITATION\s*:\s*(\S.*)", re.I)

GUARDED_EXT = (".bib", ".bibtex", ".tex")

# Generated by /papers -- never authored, and blocking them blocks the repair path.
GENERATED_BASENAMES = {"references.bib"}

DEFAULT_LIB_CANDIDATES = ["~/Papers", "~/papers-lib"]
LIB_CONFIG = "~/.config/papers/lib"
PROFILE = os.environ.get("PAPERS_PROFILE") or "~/.config/papers/profile.json"


def papers_lib():
    """Resolve the papers library the same way papers.py's resolve_lib() does, WITHOUT importing
    it -- the hook must work on a machine where the repo is not checked out."""
    env = os.environ.get("PAPERS_LIB")
    if env:
        return [os.path.realpath(os.path.expanduser(env))]
    out = []
    try:
        p = json.load(open(os.path.expanduser(PROFILE), encoding="utf-8")).get("library")
        if p:
            out.append(os.path.realpath(os.path.expanduser(p)))
    except (OSError, ValueError, AttributeError):
        pass
    cfg = os.path.expanduser(LIB_CONFIG)
    if os.path.isfile(cfg):
        try:
            p = open(cfg, encoding="utf-8").read().strip()
            if p:
                out.append(os.path.realpath(os.path.expanduser(p)))
        except OSError:
            pass
    for cand in DEFAULT_LIB_CANDIDATES:
        d = os.path.realpath(os.path.expanduser(cand))
        if os.path.isfile(os.path.join(d, "library.db")):
            out.append(d)
    return out


def under_library(path):
    real = os.path.realpath(path)
    for lib in papers_lib():
        if real == lib or real.startswith(lib + os.sep):
            return True
    return False


def keys_in(text):
    out = set()
    for m in BIB_KEY.finditer(text or ""):
        k = (m.group(1) or m.group(2) or "").strip()
        if k:
            out.add(k)
    return out


def record(entry):
    try:
        os.makedirs(os.path.dirname(LOG), exist_ok=True)
        with open(LOG, "a") as fh:
            fh.write(json.dumps(entry) + "\n")
    except Exception:
        pass                                   # logging must never break a session


def deny(reason):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": reason}}))
    sys.exit(0)


MESSAGE = (
    "STOP -- this writes a citation BY HAND, and that is the exact path that put four wrong "
    "entries into an accepted manuscript (2026-08-14).\n\n"
    "Two of those DOIs were wrong by two characters and pointed at unrelated papers; one denoted "
    "a paper that does not exist; all four had paraphrased titles and truncated author lists. "
    "The library HELD THE CORRECT VALUES for two of them. The entries were typed, not fetched.\n\n"
    "Paraphrased title + truncated authors + a plausible-but-wrong DOI is the signature of "
    "metadata recalled from memory. If you are composing these fields rather than copying them "
    "from a fetch you just ran, you are producing that signature right now.\n\n"
    "DO THIS INSTEAD -- add the paper to the library, then export:\n"
    "    papers add <doi|arxiv|bibcode>      # fetches from Crossref / arXiv / NASA ADS\n"
    "    papers bib                          # regenerates references.bib\n"
    "Then \\cite{} the key it gives you. The entry is fetched from an authority, it is verified "
    "on admission, and every other manuscript in the group gets the same correct record.\n\n"
    "GENUINELY NO IDENTIFIER? A book chapter, a thesis, a private communication, an old "
    "conference proceeding -- those are real, and this guard is not a dead end. Declare it:\n"
    "    % HAND-CITATION: <why this one cannot be fetched>\n"
    "on its own line in the file. That is logged and auditable, not a silent bypass."
)


def check(tool_name, path, new_text, old_text=""):
    """Return (decision, detail). decision is 'allow' or 'deny'. Pure -- the selftest drives it."""
    if tool_name not in ("Write", "Edit", "MultiEdit", "NotebookEdit"):
        return "allow", "not a write tool"
    if not new_text:
        return "allow", "no content"

    ext = os.path.splitext(path)[1].lower()
    base = os.path.basename(path)

    if ext == ".bbl":
        return "allow", "compiled output (.bbl), not authored"
    if ext not in GUARDED_EXT:
        return "allow", "not a bibliography file"
    if base in GENERATED_BASENAMES or under_library(path):
        return "allow", "generated by /papers"
    if base == os.path.basename(__file__):
        return "allow", "the guard itself"

    hatch = ESCAPE_HATCH.search(new_text)
    if hatch:
        return "allow-declared", hatch.group(1).strip()

    if ext == ".bib":
        hit = BIB_ENTRY.search(new_text)
    else:                                        # .tex: both forms occur
        hit = BIBITEM.search(new_text) or BIB_ENTRY.search(new_text)
    if not hit:
        return "allow", "no citation entry in the new content"

    # A reflow/move re-writes keys that already exist; only NEW citations are blocked.
    new_keys = keys_in(new_text)
    if old_text and new_keys and new_keys <= keys_in(old_text):
        return "allow", "existing keys reformatted, no new citation"

    return "deny", ",".join(sorted(new_keys)) or hit.group(0)


def main():
    if "--log" in sys.argv:
        if not os.path.exists(LOG):
            print("no declared hand-citations yet — %s does not exist" % LOG)
            return 0
        for line in open(LOG):
            try:
                d = json.loads(line)
            except Exception:
                continue
            print("%-22s %-40s %s" % (d.get("when", "?"), d.get("path", "?"), d.get("detail", "")))
        return 0
    if "--selftest" in sys.argv:
        return selftest()

    try:
        data = json.load(sys.stdin)
    except Exception:
        return 0                                 # never break the session on a parse problem

    ti = data.get("tool_input") or {}
    path = ti.get("file_path") or ti.get("notebook_path") or ""
    new_text = ti.get("content") or ti.get("new_string") or ti.get("new_source") or ""
    old_text = ti.get("old_string") or ""

    decision, detail = check(data.get("tool_name"), path, new_text, old_text)

    if decision == "allow-declared":
        import datetime
        record({"when": datetime.datetime.now().isoformat(timespec="seconds"),
                "path": path, "detail": detail, "session": data.get("session_id", "")})
        return 0
    if decision == "deny":
        import datetime
        record({"when": datetime.datetime.now().isoformat(timespec="seconds"),
                "path": path, "detail": "BLOCKED: " + detail, "session": data.get("session_id", "")})
        deny(MESSAGE)
    return 0


# --------------------------------------------------------------------------------------------
# Selftest. Both halves are required: a guard that has only ever passed proves nothing, and a
# guard that has only ever blocked gets switched off. Cases marked MUST-BLOCK are the negative
# controls -- deliberately broken input that the guard has to reject.
# --------------------------------------------------------------------------------------------
ENTRY = ("@article{reindl2017stingray,\n"
         "  title = {Discovery of a strong magnetic field in the Stingray nebula},\n"
         "  author = {Reindl, N. and others},\n"
         "  doi = {10.1093/mnrasl/slw177},\n}\n")

CASES = [
    # (label, tool, path, new_text, old_text, expect)
    ("MUST-BLOCK  @article into a .bib",
     "Write", "/tmp/scratch/refs.bib", ENTRY, "", "deny"),
    ("MUST-BLOCK  \\bibitem into a .tex",
     "Write", "/tmp/scratch/ms.tex",
     "\\begin{thebibliography}{9}\n\\bibitem{reindl2017} Reindl et al. 2017\n", "", "deny"),
    ("MUST-BLOCK  @article appended via Edit",
     "Edit", "/tmp/scratch/refs.bib", ENTRY, "@article{other2020,\n title={x},\n}\n", "deny"),
    ("MUST-BLOCK  uppercase @ARTICLE",
     "Write", "/tmp/scratch/refs.bib", ENTRY.replace("@article", "@ARTICLE"), "", "deny"),
    ("MUST-BLOCK  @inproceedings",
     "Write", "/tmp/scratch/refs.bib", ENTRY.replace("@article", "@inproceedings"), "", "deny"),
    ("MUST-BLOCK  \\bibitem[label]{key} form",
     "Write", "/tmp/scratch/ms.tex", "\\bibitem[Reindl et al.(2017)]{reindl2017} ...", "", "deny"),

    ("must-allow  references.bib (generated by /papers)",
     "Write", "/tmp/scratch/references.bib", ENTRY, "", "allow"),
    ("must-allow  a file inside the papers library",
     "Write", "/tmp/papers-hook-selftest-lib/somefile.bib", ENTRY, "", "allow"),
    ("must-allow  .bbl compiler output",
     "Write", "/tmp/scratch/ms.bbl", "\\bibitem{reindl2017} Reindl, N. 2017", "", "allow"),
    ("must-allow  declared escape hatch",
     "Write", "/tmp/scratch/refs.bib",
     "% HAND-CITATION: PhD thesis, no DOI exists\n" + ENTRY, "", "allow-declared"),
    ("must-allow  prose about bibtex in markdown",
     "Write", "/tmp/scratch/report.md", "Example: `@article{key, title={x}}`", "", "allow"),
    ("must-allow  reformatting an existing entry",
     "Edit", "/tmp/scratch/refs.bib", ENTRY, ENTRY.replace("  ", " "), "allow"),
    ("must-allow  .tex with no citation content",
     "Write", "/tmp/scratch/ms.tex", "\\section{Results}\nWe find \\cite{reindl2017}.", "", "allow"),
    ("must-allow  reading/moving is not a write",
     "Read", "/tmp/scratch/refs.bib", ENTRY, "", "allow"),
]


def selftest():
    os.environ["PAPERS_LIB"] = "/tmp/papers-hook-selftest-lib"   # the library the cases assume
    width = max(len(c[0]) for c in CASES)
    bad = 0
    for label, tool, path, new_text, old_text, expect in CASES:
        got, detail = check(tool, path, new_text, old_text)
        ok = (got == expect)
        if not ok:
            bad += 1
        print("%s  %-*s  expect=%-14s got=%-14s %s"
              % ("PASS" if ok else "FAIL", width, label, expect, got,
                 "" if ok else "<-- REGRESSION"))
    print("\n%d/%d passed" % (len(CASES) - bad, len(CASES)))
    if bad:
        print("SELFTEST FAILED — do not ship this hook until every case passes.")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
